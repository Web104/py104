# Opérations mathématiques

a = 15
b = 4
print("Addition :", a + b)
print("Soustraction :", a - b)
print("Multiplication", a * b)
print("Division", a / b)        # Division classiques
print("Division entière :", a // b)
print("Modulo :", a % b)        # Rested de la division
print("Puissance :", a ** 2)

# Chaînes de caractères
prenom = "Abdoul" 
nom = "Rachid"

# Ancienne façon (moins recommandée aujourd'hui)
print("Je m'appelle " + prenom + " " + nom)

# Nouvelle façon moderne : f-strings (très importante)  en python 3.6+
print(f"Je m'appelle {prenom} {nom}")
print(f"J'ai {2026-2002} ans en 2026")

